package DynamicProgramming._122BestTimeToBuyAndSellStockII;

// 122. Лучшее время для покупки и продажи акций II
// Вам дан целочисленный массив prices, где prices[i] — цена определённой акции в ith-й день.
//Каждый день вы можете принимать решение о покупке и/или продаже акций.
// В любой момент времени вы можете владеть не более чем одной акцией.
// Однако вы можете купить акцию, а затем сразу же продать её в тот же день.
//Найдите и верните прибыль, которую вы можете получить
// Example 1:
//Input: prices = [7,1,5,3,6,4]
//Output: 7
//Explanation: Buy on day 2 (price = 1) and sell on day 3 (price = 5), profit = 5-1 = 4.
//Then buy on day 4 (price = 3) and sell on day 5 (price = 6), profit = 6-3 = 3.
//Total profit is 4 + 3 = 7.
//Example 2:
//Input: prices = [1,2,3,4,5]
//Output: 4
//Explanation: Buy on day 1 (price = 1) and sell on day 5 (price = 5), profit = 5-1 = 4.
//Total profit is 4.
//Example 3:
//
//Input: prices = [7,6,4,3,1]
//Output: 0
//Explanation: There is no way to make a positive profit, so we never buy the stock to achieve the maximum profit of 0.
public class Solution {
    // time O(n), space O(1)
    // Альтернативный метод с использованием подхода "пиков и впадин"
    // Более подробная версия с явным указанием логики покупки/продажи
    public int maxProfit(int[] prices) {
        int n = prices.length; // Получаем количество дней
        if (n < 2) return 0; // Если меньше 2 дней, торговля невозможна

        int totalProfit = 0; // Инициализируем общую прибыль
        int buyPrice = 0; // Цена покупки
        boolean holding = false; // Флаг, показывающий, есть ли акция в портфеле

        for (int i = 0; i < n - 1; i++) {
            if (!holding && prices[i] < prices[i + 1]) {
                // Если у нас нет акции и цена завтра будет выше
                buyPrice = prices[i]; // Покупаем сегодня
                holding = true; // Теперь у нас есть акция
            } else if (holding && prices[i] > prices[i + 1]) {
                // Если у нас есть акция и цена завтра будет ниже
                totalProfit += prices[i] - buyPrice; // Продаем сегодня
                holding = false; // Теперь у нас нет акции
            }
        }
        // Если в конце цикла у нас все еще есть акция, продаем ее по последней цене
        if (holding) {
            totalProfit += prices[n - 1] - buyPrice;
        }
        return totalProfit;
    }

    // Основной метод для расчета максимальной прибыли
    // Временная сложность: O(n), где n - количество дней
    // Пространственная сложность: O(1) - используем только константную память
    public int maxProfit1(int[] prices) {
        // Инициализируем общую прибыль как 0
        int totalProfit = 0;
        // Проходим по всем дням, начиная со второго
        for (int i = 1; i < prices.length; i++) {
            // Если цена сегодня выше, чем вчера, есть возможность получить прибыль
            if (prices[i] > prices[i - 1]) {
                // Добавляем разницу цен к общей прибыли
                // Это эквивалентно покупке вчера и продаже сегодня
                totalProfit += prices[i] - prices[i - 1];
            }
            // Если цена не выросла, просто переходим к следующему дню
            // Нет необходимости совершать сделку
        }
        // Возвращаем общую прибыль
        return totalProfit;
    }
    // Объяснение алгоритма:
    //Почему простой подход работает (метод maxProfit):
    //Основная идея: Мы можем получить максимальную прибыль, покупая и продавая каждый раз, когда цена растет.
    //Математическое обоснование:
    //Если цена постоянно растет: [1,2,3,4,5]
    //Прибыль = (2-1) + (3-2) + (4-3) + (5-4) = 4
    //Это равно 5-1 = 4
    //Каждая положительная разница между последовательными днями добавляется к прибыли
    //Оптимальность: Этот подход гарантирует максимальную прибыль, так как мы извлекаем выгоду из каждого повышения цены.
    //Ключевые моменты:
    //Мы можем покупать и продавать в тот же день
    //Мы можем совершать неограниченное количество сделок
    //Мы можем владеть только одной акцией одновременно
    //Простой перебор всех положительных разниц дает оптимальный результат
    //Это решение оптимально как по времени (O(n)), так и по памяти (O(1)).


    public static void main(String[] args) {
        int[] nums = {7, 1, 5, 3, 6, 4};
        System.out.println(new Solution().maxProfit(nums));
    }
}
