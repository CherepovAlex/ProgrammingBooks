package DynamicProgramming._118PascalsTriangle;

import java.util.ArrayList;
import java.util.List;
// 118. Треугольник Паскаля
// Для заданного целого числа numRows верните первые numRows строк треугольника Паскаля.
// В треугольнике Паскаля каждое число является суммой двух чисел, расположенных непосредственно над ним,
// как показано на рисунке:
// Example 1:
//Input: numRows = 5
//Output: [[1],[1,1],[1,2,1],[1,3,3,1],[1,4,6,4,1]]
// Example 2:
//Input: numRows = 1
//Output: [[1]]
public class Solution {
    // time O(n²), space - O(n²)
     // Метод генерации треугольника Паскаля с заданным количеством строк
    // Временная сложность: O(n²), где n = numRows (сумма арифметической прогрессии)
    // Пространственная сложность: O(n²) для хранения результата
    public List<List<Integer>> generate(int numRows) {
        // Создаем список для хранения строк треугольника
        List<List<Integer>> result = new ArrayList<List<Integer>>();
        // Обрабатываем случай, когда количество строк равно 0
        if (numRows == 0) {return result;}  // / Если numRows = 0, возвращаем пустой список
        // Добавляем первую строку треугольника, которая всегда состоит из одной единицы
        result.add(new ArrayList<>(List.of(1))); // Первая строка [1]
        // Цикл для генерации остальных строк, начиная со второй (индекс 1)
        for (int i = 1; i < numRows; i++) { // Начинаем со второй строки (индекс 1)
            // Получаем предыдущую строку для вычислений
            List<Integer> previousRow = result.get(i - 1);  // Берем предыдущую строку
            // Создаем новую текущую строку
            List<Integer> currentRow = new ArrayList<>();
            // Первый элемент любой строки треугольника Паскаля всегда равен 1
            currentRow.add(1); // Первый элемент всегда 1
            // Цикл для заполнения внутренних элементов строки
            // j меняется от 1 до i-1 (не включая граничные элементы)
            for (int j = 1; j < i; j++) {   // Заполняем середину строки
                                            // Суммируем два элемента из предыдущей строки
                 // Каждый внутренний элемент равен сумме двух элементов из предыдущей строки:
                // элемента над ним слева (j-1) и элемента над ним справа (j)
                currentRow.add(previousRow.get(j - 1) + previousRow.get(j));
            }
            // Последний элемент любой строки треугольника Паскаля всегда равен 1
            currentRow.add(1); // Последний элемент всегда 1
            // Добавляем сгенерированную строку в результат
            result.add(currentRow); // Добавляем строку в результат
        }
        // Возвращаем полный треугольник Паскаля
        return result;
    }
    // Оптимизации и особенности решения:
    //Оптимальность по времени: Алгоритм имеет минимальную возможную сложность O(n²), так как для генерации
    // треугольника Паскаля необходимо заполнить все его элементы, а их количество квадратично зависит от количества строк.
    //Оптимальность по памяти: Используется O(n²) памяти только для хранения результата, что является минимальным,
    // так как нужно сохранить весь треугольник.
    //Ключевые моменты реализации:
    //Обработка граничных случаев (numRows = 0, numRows = 1)
    //Использование предыдущей строки для вычисления текущей
    //Граничные элементы всегда равны 1
    //Внутренние элементы вычисляются как сумма соответствующих элементов из предыдущей строки
    //Альтернативные подходы (не более эффективны):
    //Использование формулы сочетаний C(n,k) - аналогичная сложность
    //Рекурсивная реализация - менее эффективна из-за накладных расходов на рекурсию
    //Данное решение является каноническим и оптимальным для данной задачи.

    public static void main(String[] args) {
        int numRows = 5;
        System.out.println(new Solution().generate(numRows));
    }
}
